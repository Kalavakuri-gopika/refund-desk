from pydantic import BaseModel
from typing import List, Optional
from lemma_sdk import FunctionContext, Pod
import random

class AuditShipmentsInput(BaseModel):
    max_days_stalled: int = 3
    auto_notify: bool = True

class StalledOrderSummary(BaseModel):
    order_id: str
    customer_email: str
    carrier: str
    tracking_number: str
    shipping_status: str

class AuditShipmentsResult(BaseModel):
    scanned_orders_count: int
    delayed_orders_count: int
    tickets_created_count: int
    delayed_orders: List[StalledOrderSummary]

async def audit_delayed_shipments(ctx: FunctionContext, data: AuditShipmentsInput) -> AuditShipmentsResult:
    pod = Pod.from_env()

    # Query in_transit and delayed orders
    in_transit_resp = pod.records.list(
        "orders",
        limit=100,
        filter=[{"field": "shipping_status", "op": "in", "value": ["in_transit", "delayed"]}]
    ).to_dict()
    orders = in_transit_resp.get("items", [])

    delayed_list: List[StalledOrderSummary] = []
    created_tickets = 0

    for order in orders:
        status = order.get("shipping_status", "in_transit")
        carrier = order.get("carrier", "FedEx")
        tracking = order.get("tracking_number", "UNKNOWN")
        order_id = order.get("order_id", "ORD-000")
        email = order.get("customer_email", "customer@example.com")
        name = order.get("customer_name", "Valued Customer")

        # If flagged delayed, ensure a ticket is logged for proactive customer service
        if status == "delayed":
            delayed_list.append(
                StalledOrderSummary(
                    order_id=order_id,
                    customer_email=email,
                    carrier=carrier,
                    tracking_number=tracking,
                    shipping_status=status
                )
            )

            # Check if a ticket already exists for this order
            existing_tickets = pod.records.list(
                "tickets",
                limit=1,
                filter=[
                    {"field": "order_id", "op": "eq", "value": order_id},
                    {"field": "category", "op": "eq", "value": "shipping_delay"}
                ]
            ).to_dict().get("items", [])

            if not existing_tickets:
                pod.table("tickets").create({
                    "ticket_id": f"TCK-DELAY-{random.randint(1000, 9999)}",
                    "order_id": order_id,
                    "customer_name": name,
                    "customer_email": email,
                    "subject": f"Proactive Delivery Alert: Order {order_id} delayed with {carrier}",
                    "message": f"Carrier scan indicates delay for tracking {tracking}. Package delayed in transit.",
                    "category": "shipping_delay",
                    "status": "new",
                    "priority": "high",
                    "resolution_note": "Generated by autonomous nightly shipment sweep."
                })
                created_tickets += 1

    return AuditShipmentsResult(
        scanned_orders_count=len(orders),
        delayed_orders_count=len(delayed_list),
        tickets_created_count=created_tickets,
        delayed_orders=delayed_list
    )
